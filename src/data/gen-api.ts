// Generates src/data/http/schema.d.ts from the backend's OpenAPI document with openapi-typescript, and
// src/data/http/kiosk-routes.ts, the routes a kiosk may call (ADR 0180): every operation the backend marks
// `x-oasis-kiosk: none|actor`, plus the public operations (`security: []`), which need no session at all.
//   pnpm gen:api           write both files (reads $OASIS_OPENAPI, else $OASIS_BACKEND_PATH/docs/openapi.json, else ../backend)
//   pnpm gen:api --check   exit 1 when a committed file differs from a fresh generation (CI drift guard)
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = path.join(root, 'src/data/http/schema.d.ts')
const KIOSK_OUT = path.join(root, 'src/data/http/kiosk-routes.ts')

export function resolveSpecPath(env: NodeJS.ProcessEnv = process.env): string {
  if (env.OASIS_OPENAPI) return path.resolve(env.OASIS_OPENAPI)
  return path.resolve(root, env.OASIS_BACKEND_PATH || '../backend', 'docs/openapi.json')
}

const specSha = (specText: string): string =>
  crypto.createHash('sha256').update(specText).digest('hex').slice(0, 16)

export async function generate(specText: string): Promise<string> {
  const spec = JSON.parse(specText) as Record<string, unknown>
  const ast = await openapiTS(spec as never, { alphabetize: true, exportType: true })
  return (
    `// AUTO-GENERATED by src/data/gen-api.ts from the backend docs/openapi.json (sha256:${specSha(specText)}). DO NOT EDIT.\n` +
    '// Regenerate with `pnpm gen:api`; `pnpm gen:api --check` fails on drift.\n' +
    '/* eslint-disable */\n' +
    astToString(ast)
  )
}

const METHODS = ['get', 'put', 'post', 'patch', 'delete'] as const
export type KioskRouteMode = 'none' | 'actor' | 'public'

/** [METHOD, path template, mode] of every operation a kiosk may call, sorted by path then method. */
export function kioskRoutes(spec: { paths?: Record<string, Record<string, unknown>> }): Array<
  [string, string, KioskRouteMode]
> {
  const out: Array<[string, string, KioskRouteMode]> = []
  for (const [p, item] of Object.entries(spec.paths ?? {})) {
    for (const m of METHODS) {
      const op = item[m] as { 'x-oasis-kiosk'?: unknown; security?: unknown } | undefined
      if (!op || typeof op !== 'object') continue
      const mark = op['x-oasis-kiosk']
      if (mark === 'none' || mark === 'actor') out.push([m.toUpperCase(), p, mark])
      else if (mark !== undefined) throw new Error(`gen:api: ${m.toUpperCase()} ${p}: unknown x-oasis-kiosk ${String(mark)}`)
      else if (Array.isArray(op.security) && op.security.length === 0) out.push([m.toUpperCase(), p, 'public'])
    }
  }
  return out.sort((a, b) => (a[1] === b[1] ? a[0].localeCompare(b[0]) : a[1] < b[1] ? -1 : 1))
}

export function generateKioskRoutes(specText: string): string {
  const rows = kioskRoutes(JSON.parse(specText) as never)
  return (
    `// AUTO-GENERATED by src/data/gen-api.ts from the backend docs/openapi.json (sha256:${specSha(specText)}). DO NOT EDIT.\n` +
    '// The routes a kiosk may call (ADR 0180): `x-oasis-kiosk` none (no acting employee) or actor (a write that records who\n' +
    '// did it: X-Oasis-Employee), and the public routes. Any other route is refused by the API client before it is sent.\n' +
    '// Regenerate with `pnpm gen:api`; `pnpm gen:api --check` fails on drift.\n' +
    "export type KioskRouteMode = 'none' | 'actor' | 'public'\n\n" +
    'export const KIOSK_ROUTES: ReadonlyArray<readonly [method: string, path: string, mode: KioskRouteMode]> = [\n' +
    rows.map(([m, p, mode]) => `  ['${m}', '${p}', '${mode}'],\n`).join('') +
    ']\n'
  )
}

async function main(argv: string[]): Promise<number> {
  const specPath = resolveSpecPath()
  if (!fs.existsSync(specPath)) {
    console.error(`gen:api: ${specPath} not found. Set OASIS_OPENAPI or OASIS_BACKEND_PATH.`)
    return 2
  }
  const specText = fs.readFileSync(specPath, 'utf8')
  const files: Array<[string, string]> = [
    [OUT, await generate(specText)],
    [KIOSK_OUT, generateKioskRoutes(specText)],
  ]
  if (argv.includes('--check')) {
    let stale = 0
    for (const [file, out] of files) {
      const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
      if (have !== out) {
        console.error(
          `gen:api --check: ${path.relative(root, file)} is out of date; run \`pnpm gen:api\` and commit it.`,
        )
        stale++
      }
    }
    if (stale) return 1
    console.log('gen:api --check: up to date')
    return 0
  }
  for (const [file, out] of files) {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, out)
    console.log(`gen:api: wrote ${path.relative(root, file)} from ${specPath}`)
  }
  return 0
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then((c) => (process.exitCode = c))
}
